/** Export only absent recordings; existing Fish MCP hashes use a different signing scheme. */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { buildCatalog } from '../src/domain/audio/AudioCatalog';
import { ContentLibrary } from '../src/domain/content/ContentLibrary';
import { JsonContentSource } from '../src/domain/content/JsonContentSource';
import prompts from '../src/data/prompts.json';
import syllables from '../src/data/syllables.json';

const folder = process.argv[2];
if (!folder) throw new Error('Pass an output directory. No speech is generated by this script.');
mkdirSync(folder, { recursive: true });
const catalog = buildCatalog(new ContentLibrary(new JsonContentSource()), prompts, syllables.words.map((w) => w.text));
for (const [name, path] of [['teacher', 'src/data/audio-manifest.json'], ['josh', 'src/data/audio-josh-manifest.json']] as const) {
  const manifest = JSON.parse(readFileSync(path, 'utf8')) as Record<string, { file: string; voice: string }>;
  const clips = catalog.filter((c) => !manifest[c.key] || !existsSync(`public/${manifest[c.key]!.file}`));
  const voice = Object.values(manifest)[0]!.voice;
  const bytes = clips.reduce((n, c) => n + Buffer.byteLength(c.ttsText), 0);
  writeFileSync(`${folder}/${name}-plan.json`, JSON.stringify({ voice, model: 's2.1-pro', bytes, clips }, null, 2));
  console.log(`${name}: ${clips.length} missing clips, ${bytes} text bytes`);
}
